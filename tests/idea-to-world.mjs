import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=f=>readFileSync(path.join(root,f),'utf8');
const index=read('src/index.html'),room=read('src/idea-room.html'),script=read('src/idea-room.js'),portal=read('src/city-idea-link.js');
for(const [name,source] of [['room',script],['city portal',portal]])assert.doesNotThrow(()=>new Function(source),name+' script syntax');
assert.match(index,/src="city-idea-link.js"/,'City integration must remain loaded');
assert.match(room,/src="assets\/three.min.js"/);
assert.match(room,/src="idea-room.js"/);
assert.match(portal,/quickStart\('city'\)/,'Room exit must arrive in original City of Ideas');
assert.match(portal,/idea-room.html/,'City street must allow returning to the room');
assert.match(script,/index.html\?from=idea-room/,'Exit must return to the public city');
assert.match(script,/city-idea-room-v1/,'Carry-over state must have a stable browser-local key');
assert.match(script,/elapsedMs/,'Elapsed journey must be persisted');
assert.match(script,/thought/,'One idea must be carried to the city');
assert.doesNotMatch(script,/OPENAI_API_KEY|fetch\(/,'The prototype must not silently call external or paid AI services');
console.log('Idea-to-world prototype checks passed (static checks; browser behavior unverified).');